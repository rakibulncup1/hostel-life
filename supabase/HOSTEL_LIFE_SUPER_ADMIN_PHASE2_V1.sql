CREATE OR REPLACE FUNCTION private.consume_platform_access_code(p_purpose text,p_code text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER
SET search_path=private,public,extensions,pg_catalog
AS $$
DECLARE v_code private.platform_access_codes;
BEGIN
  IF p_purpose NOT IN ('registration','hostel_creation') OR nullif(trim(p_code),'') IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='সঠিক অনুমতি কোড দিন।';
  END IF;
  SELECT c.* INTO v_code FROM private.platform_access_codes c
  WHERE c.purpose=p_purpose
    AND c.code_hash=private.sha256_text(upper(trim(p_code)))
    AND c.revoked_at IS NULL AND c.expires_at>now() AND c.use_count<c.max_uses
  ORDER BY c.created_at DESC LIMIT 1 FOR UPDATE;
  IF v_code.id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='অনুমতি কোডটি ভুল, মেয়াদোত্তীর্ণ বা ব্যবহারসীমা শেষ।';
  END IF;
  UPDATE private.platform_access_codes SET use_count=use_count+1 WHERE id=v_code.id;
END;
$$;
REVOKE ALL ON FUNCTION private.consume_platform_access_code(text,text) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.enforce_registration_code_gate()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path=private,public,extensions,pg_catalog
AS $$
DECLARE v_required boolean; v_code text;
BEGIN
  SELECT s.registration_code_required INTO v_required FROM private.platform_settings s WHERE s.singleton_id=true;
  IF COALESCE(v_required,false) THEN
    v_code := NEW.raw_user_meta_data->>'permission_code';
    PERFORM private.consume_platform_access_code('registration',v_code);
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.enforce_registration_code_gate() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS hostel_life_registration_code_gate ON auth.users;
CREATE TRIGGER hostel_life_registration_code_gate
BEFORE INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION private.enforce_registration_code_gate();

