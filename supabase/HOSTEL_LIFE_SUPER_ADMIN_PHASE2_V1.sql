CREATE OR REPLACE FUNCTION public.platform_admin_set_gate(p_purpose text,p_required boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=private,public,pg_catalog
AS $$
BEGIN
  PERFORM private.assert_super_admin();
  IF p_purpose='registration' THEN
    UPDATE private.platform_settings SET registration_code_required=COALESCE(p_required,false),updated_by=auth.uid(),updated_at=now() WHERE singleton_id=true;
  ELSIF p_purpose='hostel_creation' THEN
    UPDATE private.platform_settings SET hostel_creation_code_required=COALESCE(p_required,false),updated_by=auth.uid(),updated_at=now() WHERE singleton_id=true;
  ELSE RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Gate type সঠিক নয়।';
  END IF;
  INSERT INTO private.platform_admin_audit_log(actor_user_id,action,entity_type,details)
  VALUES(auth.uid(),'access_gate_changed','settings',jsonb_build_object('purpose',p_purpose,'required',p_required));
  RETURN jsonb_build_object('purpose',p_purpose,'required',p_required);
END;
$$;

CREATE OR REPLACE FUNCTION public.platform_admin_generate_access_code(p_purpose text,p_ttl_minutes integer DEFAULT 1440,p_max_uses integer DEFAULT 1)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=private,public,extensions,pg_catalog
AS $$
DECLARE v_code text; v_expires timestamptz; v_id uuid;
BEGIN
  PERFORM private.assert_super_admin();
  IF p_purpose NOT IN ('registration','hostel_creation') THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='কোডের ধরন সঠিক নয়।'; END IF;
  IF p_ttl_minutes IS NULL OR p_ttl_minutes<5 OR p_ttl_minutes>10080 THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='কোডের মেয়াদ ৫ মিনিট থেকে ৭ দিনের মধ্যে হতে হবে।'; END IF;
  IF p_max_uses IS NULL OR p_max_uses<1 OR p_max_uses>1000 THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='ব্যবহারের সীমা ১ থেকে ১০০০-এর মধ্যে হতে হবে।'; END IF;
  -- Rotating a code revokes every prior code for this purpose immediately.
  UPDATE private.platform_access_codes SET revoked_at=now() WHERE purpose=p_purpose AND revoked_at IS NULL;
  v_code := upper(substr(translate(gen_random_uuid()::text,'-',''),1,20));
  v_expires := now() + make_interval(mins=>p_ttl_minutes);
  INSERT INTO private.platform_access_codes(purpose,code_hash,expires_at,max_uses,created_by)
  VALUES(p_purpose,private.sha256_text(v_code),v_expires,p_max_uses,auth.uid()) RETURNING id INTO v_id;
  INSERT INTO private.platform_admin_audit_log(actor_user_id,action,entity_type,entity_id,details)
  VALUES(auth.uid(),'access_code_generated','access_code',v_id::text,jsonb_build_object('purpose',p_purpose,'expires_at',v_expires,'max_uses',p_max_uses));
  RETURN jsonb_build_object('id',v_id,'purpose',p_purpose,'code',v_code,'expires_at',v_expires,'max_uses',p_max_uses,
    'warning','কোডটি শুধু এখন দেখানো হচ্ছে। নিরাপদ স্থানে কপি করুন।');
END;
$$;

-- Always call this wrapper from current versions of the app. The old create_hostel
-- RPC is blocked by the database trigger when a code gate is enabled.
CREATE OR REPLACE FUNCTION public.create_hostel_secure(p_name text,p_permission_code text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,private,pg_catalog
AS $$
DECLARE v_required boolean; v_result jsonb;
BEGIN
  PERFORM private.assert_authenticated();
  IF private.is_platform_user_blocked(auth.uid()) THEN RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='এই অ্যাকাউন্টটি ব্লক করা হয়েছে।'; END IF;
  SELECT s.hostel_creation_code_required INTO v_required FROM private.platform_settings s WHERE s.singleton_id=true;
  IF COALESCE(v_required,false) THEN PERFORM private.consume_platform_access_code('hostel_creation',p_permission_code); END IF;
  PERFORM set_config('hostel_life.hostel_creation_verified','true',true);
  v_result := public.create_hostel(p_name);
  PERFORM set_config('hostel_life.hostel_creation_verified','false',true);
  RETURN v_result;
END;
$$;

-- Enforce blocked users and suspended/soft-deleted messes for direct writes and
-- existing SECURITY DEFINER RPCs (triggers run under the caller's JWT context).
CREATE OR REPLACE FUNCTION private.guard_platform_write()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,private,pg_catalog
AS $$
DECLARE v_row jsonb; v_hostel uuid; v_user uuid; v_status text; v_parent uuid;
BEGIN
  IF auth.uid() IS NULL OR private.is_super_admin() THEN
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
  END IF;
  v_row := CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  v_user := NULLIF(v_row->>'user_id','')::uuid;
  v_status := v_row->>'status';
  IF TG_TABLE_NAME='hostels' THEN
    v_hostel := NULLIF(v_row->>'id','')::uuid;
  ELSE
    v_hostel := NULLIF(v_row->>'hostel_id','')::uuid;
  END IF;
  IF TG_TABLE_NAME='market_items' THEN
    v_parent := NULLIF(v_row->>'market_entry_id','')::uuid;
    SELECT me.hostel_id INTO v_hostel FROM public.market_entries me WHERE me.id=v_parent;
  ELSIF TG_TABLE_NAME='meal_request_days' THEN
    v_parent := NULLIF(v_row->>'request_id','')::uuid;
    SELECT mr.hostel_id INTO v_hostel FROM public.meal_requests mr WHERE mr.id=v_parent;
  ELSIF TG_TABLE_NAME='notification_states' THEN
    v_parent := NULLIF(v_row->>'notification_id','')::uuid;
    SELECT n.hostel_id INTO v_hostel FROM public.notifications n WHERE n.id=v_parent;
  ELSIF TG_TABLE_NAME='period_assistant_managers' THEN
    v_parent := NULLIF(v_row->>'period_id','')::uuid;
    SELECT mp.hostel_id INTO v_hostel FROM public.monthly_periods mp WHERE mp.id=v_parent;
  END IF;

  IF private.is_platform_user_blocked(auth.uid()) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='এই অ্যাকাউন্টটি প্ল্যাটফর্ম অ্যাডমিন দ্বারা ব্লক করা হয়েছে।';
  END IF;
  IF TG_TABLE_NAME='hostel_memberships' AND TG_OP<>'DELETE' AND v_user IS NOT NULL
     AND v_status='active' AND private.is_platform_user_blocked(v_user) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='ব্লক করা ব্যবহারকারীকে সক্রিয় মেম্বার হিসেবে যুক্ত করা যাবে না।';
  END IF;
  IF v_hostel IS NOT NULL AND EXISTS (
    SELECT 1 FROM private.platform_hostel_controls c WHERE c.hostel_id=v_hostel AND c.status IN ('suspended','soft_deleted')
  ) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='এই মেসটি সাময়িকভাবে স্থগিত বা বন্ধ করা হয়েছে।';
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
REVOKE ALL ON FUNCTION private.guard_platform_write() FROM PUBLIC, anon, authenticated;

DO $platform_triggers$
DECLARE v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'hostels','hostel_memberships','monthly_periods','daily_meal_days','daily_meal_records',
    'daily_meal_snapshots','ledger_transactions','market_entries','market_items','meal_requests',
    'meal_request_days','meal_late_overrides','khala_money_entries','notifications',
    'archive_edit_permissions','monthly_summaries','period_assistant_managers','notification_states'
  ] LOOP
    IF to_regclass(format('public.%I',v_table)) IS NOT NULL THEN
      EXECUTE format('DROP TRIGGER IF EXISTS hostel_life_platform_access_guard ON public.%I',v_table);
      EXECUTE format('CREATE TRIGGER hostel_life_platform_access_guard BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION private.guard_platform_write()',v_table);
    END IF;
  END LOOP;
END;
$platform_triggers$;

