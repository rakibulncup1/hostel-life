-- Super-admin must be promoted manually by the project owner in SQL Editor.
-- A signed-in browser cannot set or change profiles.role, even on its own profile.
CREATE OR REPLACE FUNCTION private.is_super_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=public,pg_catalog
AS $$
  SELECT auth.uid() IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.role='super_admin'
  );
$$;
REVOKE ALL ON FUNCTION private.is_super_admin() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.assert_super_admin()
RETURNS void LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=public,pg_catalog
AS $$
BEGIN
  IF NOT private.is_super_admin() THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Super Admin permission is required.';
  END IF;
END;
$$;
REVOKE ALL ON FUNCTION private.assert_super_admin() FROM PUBLIC, anon, authenticated;

