CREATE OR REPLACE FUNCTION public.platform_admin_get_overview()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=public,private,auth,pg_catalog
AS $$
DECLARE v_hostels bigint; v_users bigint; v_memberships bigint; v_suspended bigint; v_deleted bigint; v_blocked bigint;
BEGIN
  PERFORM private.assert_super_admin();
  SELECT count(*) INTO v_hostels FROM public.hostels;
  SELECT count(*) INTO v_users FROM auth.users;
  SELECT count(*) INTO v_memberships FROM public.hostel_memberships WHERE status='active'::public.membership_status;
  SELECT count(*) INTO v_suspended FROM private.platform_hostel_controls WHERE status='suspended';
  SELECT count(*) INTO v_deleted FROM private.platform_hostel_controls WHERE status='soft_deleted';
  SELECT count(*) INTO v_blocked FROM private.platform_user_blocks;
  RETURN jsonb_build_object('hostels',v_hostels,'users',v_users,'active_memberships',v_memberships,
    'suspended_hostels',v_suspended,'soft_deleted_hostels',v_deleted,'blocked_users',v_blocked);
END;
$$;

CREATE OR REPLACE FUNCTION public.platform_admin_list_hostels()
RETURNS TABLE(hostel_id uuid,name text,created_at timestamptz,platform_status text,member_count bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=public,private,pg_catalog
AS $$
BEGIN
  PERFORM private.assert_super_admin();
  RETURN QUERY
  SELECT h.id,h.name,h.created_at,COALESCE(c.status,'active')::text,
    (SELECT count(*) FROM public.hostel_memberships hm WHERE hm.hostel_id=h.id AND hm.status='active'::public.membership_status)
  FROM public.hostels h LEFT JOIN private.platform_hostel_controls c ON c.hostel_id=h.id
  ORDER BY h.created_at DESC;
END;
$$;

