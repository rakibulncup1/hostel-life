-- ---------------------------------------------------------------------------
-- D. Marketplace entry RPC: members can enter their own purchase; managers can
--    enter for an active member. Historical changes are handled by manager edit
--    RPC below and require the existing period/archival permission model.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.create_market_entry(
  p_entry_date date,
  p_buyer_membership_id uuid,
  p_items jsonb,
  p_credit_to_buyer boolean DEFAULT false
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,pg_catalog
AS $market_create$
DECLARE
  v_actor uuid; v_hostel uuid; v_period uuid; v_entry_id uuid; v_total numeric(14,2);
  v_buyer public.hostel_memberships;
  x record;
BEGIN
  PERFORM private.assert_authenticated();
  v_actor := private.current_membership_id(true);
  v_hostel := private.current_hostel_id(true);
  IF p_entry_date IS NULL OR p_entry_date > (now() AT TIME ZONE 'Asia/Dhaka')::date THEN
    RAISE EXCEPTION USING message='বাজারের তারিখ আজ বা তার আগের হতে হবে।';
  END IF;
  v_period := private.period_for_hostel_date(v_hostel,p_entry_date);
  IF v_period IS NULL OR NOT EXISTS (SELECT 1 FROM public.monthly_periods mp WHERE mp.id=v_period AND mp.hostel_id=v_hostel AND mp.status='running'::public.month_status) THEN
    RAISE EXCEPTION USING message='বাজার এন্ট্রির তারিখের জন্য কোনো চলমান মাস নেই।';
  END IF;
  IF NOT private.can_manage_period(v_period) AND p_buyer_membership_id IS DISTINCT FROM v_actor THEN
    RAISE EXCEPTION USING message='সাধারণ সদস্য শুধু নিজের নামে বাজার এন্ট্রি করতে পারবেন।';
  END IF;
  PERFORM private.assert_membership(p_buyer_membership_id,v_hostel,true);
  SELECT * INTO v_buyer FROM public.hostel_memberships hm WHERE hm.id=p_buyer_membership_id AND hm.hostel_id=v_hostel AND hm.status='active'::public.membership_status;
  IF v_buyer.id IS NULL THEN RAISE EXCEPTION USING message='নির্বাচিত সক্রিয় সদস্য পাওয়া যায়নি।'; END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array' OR jsonb_array_length(p_items)=0 THEN
    RAISE EXCEPTION USING message='কমপক্ষে একটি বাজারের আইটেম দিন।';
  END IF;
  IF EXISTS (SELECT 1 FROM jsonb_array_elements(p_items) AS e(value)
    WHERE nullif(trim(e.value->>'item_name'),'') IS NULL OR COALESCE(e.value->>'amount','')='' ) THEN
    RAISE EXCEPTION USING message='প্রতিটি আইটেমের নাম ও টাকার পরিমাণ দিতে হবে।';
  END IF;
  BEGIN
    IF EXISTS (SELECT 1 FROM jsonb_to_recordset(p_items) AS i(item_name text,quantity text,amount numeric)
      WHERE i.amount IS NULL OR i.amount<0 OR i.amount>100000000) THEN
      RAISE EXCEPTION USING message='বাজারের টাকার পরিমাণ সঠিক নয়।';
    END IF;
  EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
    RAISE EXCEPTION USING message='বাজারের টাকার পরিমাণ সঠিক নয়।';
  END;
  SELECT round(COALESCE(sum(i.amount),0),2) INTO v_total
  FROM jsonb_to_recordset(p_items) AS i(item_name text,quantity text,amount numeric);
  IF v_total<=0 THEN RAISE EXCEPTION USING message='মোট বাজারের পরিমাণ শূন্যের বেশি হতে হবে।'; END IF;
  INSERT INTO public.market_entries(hostel_id,period_id,buyer_membership_id,entry_date,total_amount,credit_to_buyer,status,created_by)
  VALUES(v_hostel,v_period,p_buyer_membership_id,p_entry_date,v_total,COALESCE(p_credit_to_buyer,false),'active'::public.market_status,v_actor)
  RETURNING id INTO v_entry_id;
  INSERT INTO public.market_items(market_entry_id,serial_no,item_name,quantity,amount)
  SELECT v_entry_id,e.ord::int,trim(e.value->>'item_name'),COALESCE(e.value->>'quantity',''),(e.value->>'amount')::numeric
  FROM jsonb_array_elements(p_items) WITH ORDINALITY AS e(value,ord);
  IF COALESCE(p_credit_to_buyer,false) THEN
    INSERT INTO public.ledger_transactions(hostel_id,period_id,member_id,ledger_type,ledger_group,amount,reference_type,reference_id,description,created_by,entry_date)
    VALUES(v_hostel,v_period,p_buyer_membership_id,'market_deposit'::public.ledger_type,'deposit'::public.ledger_group,v_total,
      'market_entry',v_entry_id,'বাজারের টাকা ডিপোজিট হিসেবে যুক্ত',v_actor,p_entry_date);
  END IF;
  RETURN jsonb_build_object('market_entry_id',v_entry_id,'total_amount',v_total,'period_id',v_period,'status','active');
END;
$market_create$;
REVOKE ALL ON FUNCTION public.create_market_entry(date,uuid,jsonb,boolean) FROM PUBLIC, anon;
