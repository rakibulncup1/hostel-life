-- Hash with SHA-256; the unhashed code is returned once only to the super-admin.
CREATE OR REPLACE FUNCTION private.sha256_text(p_text text)
RETURNS text LANGUAGE plpgsql IMMUTABLE SECURITY DEFINER
SET search_path=extensions,public,pg_catalog
AS $$
DECLARE v_hash text;
BEGIN
  IF to_regprocedure('extensions.digest(bytea,text)') IS NOT NULL THEN
    EXECUTE 'SELECT encode(extensions.digest(convert_to($1, ''UTF8''), ''sha256''), ''hex'')' INTO v_hash USING p_text;
  ELSIF to_regprocedure('public.digest(bytea,text)') IS NOT NULL THEN
    EXECUTE 'SELECT encode(public.digest(convert_to($1, ''UTF8''), ''sha256''), ''hex'')' INTO v_hash USING p_text;
  ELSE
    RAISE EXCEPTION 'pgcrypto digest() is unavailable; do not enable access-code gates until pgcrypto is installed.';
  END IF;
  RETURN v_hash;
END;
$$;
REVOKE ALL ON FUNCTION private.sha256_text(text) FROM PUBLIC, anon, authenticated;

