CREATE OR REPLACE FUNCTION public.platform_admin_generate_access_code(p_purpose text,p_ttl_minutes integer DEFAULT 1440,p_max_uses integer DEFAULT 1)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=private,public,extensions,pg_catalog
AS $$
DECLARE v_code text; v_expires timestamptz; v_id uuid;
BEGIN
  PERFORM private.assert_super_admin();
  IF p_purpose NOT IN ('registration','hostel_creation') THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='কোডের ধরন সঠিক নয়।'; END IF;
  IF p_ttl_minutes IS NULL OR p_ttl_minutes<5 OR p_ttl_minutes>10080 THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='কোডের মেয়াদ ৫ মিনিট থেকে ৭ দিনের মধ্যে হতে হবে।'; END IF;
  IF p_max_uses IS NULL OR p_max_uses<1 OR p_max_uses>1000 THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='ব্যবহারের সীমা ১ থেকে ১০০০-এর মধ্যে হতে হবে।'; END IF;
  -- Rotating a code revokes every prior code for this purpose immediately.
  UPDATE private.platform_access_codes SET revoked_at=now() WHERE purpose=p_purpose AND revoked_at IS NULL;
  v_code := upper(substr(translate(gen_random_uuid()::text,'-',''),1,20));
  v_expires := now() + make_interval(mins=>p_ttl_minutes);
  INSERT INTO private.platform_access_codes(purpose,code_hash,expires_at,max_uses,created_by)
  VALUES(p_purpose,private.sha256_text(v_code),v_expires,p_max_uses,auth.uid()) RETURNING id INTO v_id;
  INSERT INTO private.platform_admin_audit_log(actor_user_id,action,entity_type,entity_id,details)
  VALUES(auth.uid(),'access_code_generated','access_code',v_id::text,jsonb_build_object('purpose',p_purpose,'expires_at',v_expires,'max_uses',p_max_uses));
  RETURN jsonb_build_object('id',v_id,'purpose',p_purpose,'code',v_code,'expires_at',v_expires,'max_uses',p_max_uses,
    'warning','কোডটি শুধু এখন দেখানো হচ্ছে। নিরাপদ স্থানে কপি করুন।');
END;
$$;

-- Always call this wrapper from current versions of the app. The old create_hostel
