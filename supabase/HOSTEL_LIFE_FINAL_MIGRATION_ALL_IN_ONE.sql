$$;

CREATE OR REPLACE FUNCTION public.platform_admin_set_user_blocked(p_user_id uuid,p_blocked boolean,p_reason text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,private,pg_catalog
AS $$
DECLARE v_count integer := 0;
BEGIN
  PERFORM private.assert_super_admin();
  IF p_user_id IS NULL OR p_user_id=auth.uid() THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='নিজের Super Admin অ্যাকাউন্ট ব্লক করা যাবে না।'; END IF;
  IF NOT EXISTS(SELECT 1 FROM auth.users u WHERE u.id=p_user_id) THEN RAISE EXCEPTION USING MESSAGE='ব্যবহারকারী পাওয়া যায়নি।'; END IF;
  IF p_blocked THEN
    INSERT INTO private.platform_user_blocks(user_id,reason,blocked_by,blocked_at)
    VALUES(p_user_id,nullif(trim(p_reason),''),auth.uid(),now())
    ON CONFLICT(user_id) DO UPDATE SET reason=EXCLUDED.reason,blocked_by=EXCLUDED.blocked_by,blocked_at=now();
    INSERT INTO private.platform_user_block_memberships(membership_id,previous_status,previous_deactivated_at,previous_deactivated_by)
    SELECT hm.id,hm.status::text,hm.deactivated_at,hm.deactivated_by
    FROM public.hostel_memberships hm WHERE hm.user_id=p_user_id AND hm.status='active'::public.membership_status
    ON CONFLICT(membership_id) DO NOTHING;
    UPDATE public.hostel_memberships hm SET status='inactive'::public.membership_status,deactivated_at=now(),deactivated_by=NULL,updated_at=now()
    WHERE hm.user_id=p_user_id AND hm.status='active'::public.membership_status;
  ELSE
    IF NOT EXISTS(SELECT 1 FROM private.platform_user_blocks b WHERE b.user_id=p_user_id) THEN
      RETURN jsonb_build_object('user_id',p_user_id,'blocked',false,'changed',false);
    END IF;
    UPDATE public.hostel_memberships hm SET
      status=bu.previous_status::public.membership_status,
      deactivated_at=bu.previous_deactivated_at,
      deactivated_by=bu.previous_deactivated_by,
      reactivated_at=CASE WHEN bu.previous_status='active' THEN now() ELSE hm.reactivated_at END,
      updated_at=now()
    FROM private.platform_user_block_memberships bu
    WHERE hm.id=bu.membership_id AND hm.user_id=p_user_id;
    DELETE FROM private.platform_user_block_memberships bu WHERE EXISTS(SELECT 1 FROM public.hostel_memberships hm WHERE hm.id=bu.membership_id AND hm.user_id=p_user_id);
    DELETE FROM private.platform_user_blocks WHERE user_id=p_user_id;
  END IF;
  SELECT count(*) INTO v_count FROM public.hostel_memberships hm WHERE hm.user_id=p_user_id AND hm.status='inactive'::public.membership_status;
  INSERT INTO private.platform_admin_audit_log(actor_user_id,action,entity_type,entity_id,details)
  VALUES(auth.uid(),CASE WHEN p_blocked THEN 'user_blocked' ELSE 'user_unblocked' END,'user',p_user_id::text,jsonb_build_object('reason',p_reason,'inactive_memberships',v_count));
  RETURN jsonb_build_object('user_id',p_user_id,'blocked',p_blocked,'inactive_memberships',v_count);
END;
$$;

