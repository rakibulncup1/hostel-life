-- ---------------------------------------------------------------------------
-- E. Append-only correction for deposits and other expenses. Keep the original
--    ledger row intact, add a signed adjustment row, and calculate the effective
--    amount including previous adjustments to prevent repeated-edit drift.
-- ---------------------------------------------------------------------------
-- FIX: PostgreSQL cannot change an existing function's return type with CREATE OR REPLACE.
-- Drop only this exact overload (no CASCADE, so dependent objects are protected), then recreate it.
DROP FUNCTION IF EXISTS public.manager_adjust_transaction(uuid,numeric,text);

CREATE FUNCTION public.manager_adjust_transaction(
  p_transaction_id uuid,
  p_new_amount numeric,
  p_description text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,pg_catalog
AS $adjust_transaction$
DECLARE
  v_actor uuid; v_hostel uuid; v_tx public.ledger_transactions;
  v_effective numeric(14,2); v_target numeric(14,2); v_delta numeric(14,2);
  v_group public.ledger_group;
BEGIN
  PERFORM private.assert_authenticated();
  v_actor := private.current_membership_id(true);
  v_hostel := private.current_hostel_id(true);
  IF p_new_amount IS NULL OR abs(p_new_amount)>1000000000 THEN
    RAISE EXCEPTION USING message='সংশোধিত টাকার পরিমাণ সঠিক নয়।';
  END IF;
  SELECT * INTO v_tx FROM public.ledger_transactions lt
   WHERE lt.id=p_transaction_id AND lt.hostel_id=v_hostel
     AND lt.ledger_type IN ('deposit'::public.ledger_type,'other_expense'::public.ledger_type)
   FOR UPDATE;
  IF v_tx.id IS NULL THEN RAISE EXCEPTION USING message='সম্পাদনযোগ্য ডিপোজিট/অন্যান্য খরচ পাওয়া যায়নি।'; END IF;
  IF NOT private.can_manage_period(v_tx.period_id) THEN
    RAISE EXCEPTION USING message='এই হিসাব সংশোধনের অনুমতি নেই।';
  END IF;
  IF v_tx.ledger_type='deposit'::public.ledger_type AND p_new_amount<=0 THEN
    RAISE EXCEPTION USING message='ডিপোজিটের পরিমাণ শূন্যের বেশি হতে হবে।';
  ELSIF v_tx.ledger_type='other_expense'::public.ledger_type AND p_new_amount>=0 THEN
    RAISE EXCEPTION USING message='অন্যান্য খরচের সংশোধিত পরিমাণ শূন্যের কম হতে হবে।';
  END IF;
  v_target := round(p_new_amount,2);
  SELECT round(v_tx.amount + COALESCE(sum(adj.amount),0),2) INTO v_effective
  FROM public.ledger_transactions adj
  WHERE adj.parent_transaction_id=v_tx.id AND adj.reference_type='transaction_adjustment';
  -- The aggregate query above returns no row when no child exists; coalesce it back to original.
  v_effective := COALESCE(v_effective,v_tx.amount);
  v_delta := round(v_target-v_effective,2);
  IF v_delta<>0 THEN
    v_group := CASE WHEN v_delta>0 THEN 'deposit'::public.ledger_group ELSE 'expense'::public.ledger_group END;
    INSERT INTO public.ledger_transactions(
      hostel_id,period_id,member_id,ledger_type,ledger_group,amount,reference_type,reference_id,
      parent_transaction_id,description,created_by,entry_date
    ) VALUES(
      v_tx.hostel_id,v_tx.period_id,v_tx.member_id,'adjustment'::public.ledger_type,v_group,v_delta,
      'transaction_adjustment',v_tx.id,v_tx.id,
      COALESCE(NULLIF(trim(p_description),''),'ম্যানেজার কর্তৃক হিসাব সংশোধন'),v_actor,v_tx.entry_date
    );
  END IF;
  RETURN jsonb_build_object('transaction_id',v_tx.id,'original_amount',v_tx.amount,'previous_effective_amount',v_effective,
    'new_amount',v_target,'adjustment_amount',v_delta,'unchanged',(v_delta=0));
END;
$adjust_transaction$;
REVOKE ALL ON FUNCTION public.manager_adjust_transaction(uuid,numeric,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.manager_adjust_transaction(uuid,numeric,text) TO authenticated;

-- ---------------------------------------------------------------------------
-- F. Manager role can be changed after the current period is closed. Running
--    period's historical manager-at-start/close fields are left untouched.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.change_manager(p_new_membership_id uuid)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,pg_catalog
AS $change_manager$
DECLARE
  v_actor uuid; v_hostel uuid; v_target public.hostel_memberships; v_period public.monthly_periods;
BEGIN
  PERFORM private.assert_authenticated();
  v_actor := private.current_membership_id(true);
  v_hostel := private.current_hostel_id(true);
  IF v_actor IS NULL THEN RAISE EXCEPTION USING message='সক্রিয় সদস্যের পরিচয় পাওয়া যায়নি।'; END IF;
  SELECT * INTO v_target FROM public.hostel_memberships hm
   WHERE hm.id=p_new_membership_id AND hm.hostel_id=v_hostel AND hm.status='active'::public.membership_status
   FOR UPDATE;
  IF v_target.id IS NULL THEN RAISE EXCEPTION USING message='নতুন ম্যানেজার হিসেবে সক্রিয় সদস্য নির্বাচন করুন।'; END IF;
  IF v_target.id=v_actor THEN RAISE EXCEPTION USING message='আপনি ইতোমধ্যে নির্বাচিত সদস্য। অন্য সদস্য নির্বাচন করুন।'; END IF;
  SELECT * INTO v_period FROM public.monthly_periods mp WHERE mp.hostel_id=v_hostel AND mp.status='running'::public.month_status
   ORDER BY mp.start_date DESC,mp.created_at DESC LIMIT 1 FOR UPDATE;
  IF v_period.id IS NOT NULL THEN
    IF v_period.primary_manager_membership_id IS NOT NULL THEN
      IF v_period.primary_manager_membership_id<>v_actor THEN
        RAISE EXCEPTION USING message='চলমান মাসের প্রধান ম্যানেজারই ম্যানেজার পরিবর্তন করতে পারবেন।';
      END IF;
    ELSIF NOT private.is_manager(v_hostel) THEN
      RAISE EXCEPTION USING message='ম্যানেজার পরিবর্তনের অনুমতি নেই।';
    END IF;
  ELSE
    IF NOT private.is_manager(v_hostel) THEN
      RAISE EXCEPTION USING message='মাস বন্ধ থাকলে সক্রিয় মেস ম্যানেজারই পরবর্তী ম্যানেজার নির্বাচন করতে পারবেন।';
    END IF;
  END IF;

  UPDATE public.hostel_memberships SET role='member'::public.membership_role,updated_at=now()
   WHERE hostel_id=v_hostel AND status='active'::public.membership_status AND role='manager'::public.membership_role;
  UPDATE public.hostel_memberships SET role='manager'::public.membership_role,updated_at=now()
   WHERE id=v_target.id;
  IF v_period.id IS NOT NULL THEN
    UPDATE public.monthly_periods SET primary_manager_membership_id=v_target.id,updated_at=now() WHERE id=v_period.id;
  END IF;
  RETURN jsonb_build_object('hostel_id',v_hostel,'new_manager_membership_id',v_target.id,'running_period_updated',v_period.id IS NOT NULL);
END;
$change_manager$;
REVOKE ALL ON FUNCTION public.change_manager(uuid) FROM PUBLIC, anon;
