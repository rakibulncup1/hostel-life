-- ---------------------------------------------------------------------------
-- C. Manager edit of a submitted correction/late request; it keeps the same
--    request id/status and records an audit entry + targeted notification.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.manager_update_submitted_meal_request(
  p_request_id uuid,
  p_days jsonb,
  p_note text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,pg_catalog
AS $submitted_request_edit$
DECLARE
  v_req public.meal_requests;
  v_actor uuid;
  v_hostel uuid;
  v_period public.monthly_periods;
  v_before jsonb := '[]'::jsonb;
  v_after jsonb := '[]'::jsonb;
  v_expected integer;
  v_count integer;
  d record;
BEGIN
  PERFORM private.assert_authenticated();
  v_actor := private.current_membership_id(true);
  v_hostel := private.current_hostel_id(true);

  IF jsonb_typeof(p_days) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION USING message='মিলের দিনের তালিকা সঠিক নয়।';
  END IF;

  SELECT * INTO v_req FROM public.meal_requests mr
   WHERE mr.id=p_request_id AND mr.hostel_id=v_hostel
   FOR UPDATE;
  IF v_req.id IS NULL THEN RAISE EXCEPTION USING message='রিকোয়েস্টটি পাওয়া যায়নি।'; END IF;
  IF v_req.status <> 'submitted'::public.request_status
     OR NOT (v_req.request_type='correction'::public.meal_request_type OR v_req.is_late_request) THEN
    RAISE EXCEPTION USING message='শুধু জমা দেওয়া correction/late request এভাবে এডিট করা যাবে।';
  END IF;
  IF NOT private.can_manage_period(v_req.period_id) THEN
    RAISE EXCEPTION USING message='এই রিকোয়েস্ট পরিবর্তনের অনুমতি নেই।';
  END IF;
  SELECT * INTO v_period FROM public.monthly_periods mp WHERE mp.id=v_req.period_id AND mp.hostel_id=v_hostel;
  IF v_period.id IS NULL OR v_period.status <> 'running'::public.month_status THEN
    RAISE EXCEPTION USING message='পুরোনো/বন্ধ মাসের অনুরোধ এই পথে এডিট করা যাবে না। Archive correction ব্যবহার করুন।';
  END IF;

  v_expected := v_req.end_date-v_req.start_date+1;
  SELECT count(*)::int INTO v_count FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric);
  IF v_count IS DISTINCT FROM v_expected THEN RAISE EXCEPTION USING message='রিকোয়েস্টের প্রতিটি দিনের মিল দিতে হবে।'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)
    GROUP BY x.meal_date HAVING count(*)>1
  ) THEN RAISE EXCEPTION USING message='একই তারিখ একাধিকবার দেওয়া যাবে না।'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)
    WHERE x.meal_date<v_req.start_date OR x.meal_date>v_req.end_date
       OR x.breakfast IS NULL OR x.lunch IS NULL OR x.dinner IS NULL
       OR x.breakfast<0 OR x.lunch<0 OR x.dinner<0
       OR x.breakfast>50 OR x.lunch>50 OR x.dinner>50
  ) THEN RAISE EXCEPTION USING message='তারিখ বা মিলের পরিমাণ সঠিক নয়।'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)
    LEFT JOIN public.daily_meal_days dmd ON dmd.hostel_id=v_hostel AND dmd.period_id=v_req.period_id AND dmd.meal_date=x.meal_date
    WHERE dmd.id IS NULL OR dmd.status='finalized'::public.meal_day_status OR now()>=dmd.finalizes_at
  ) THEN RAISE EXCEPTION USING message='চূড়ান্ত বা সময়সীমা পার হওয়া দিনের অনুরোধ এই পথে পরিবর্তন করা যাবে না।'; END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('manager-submitted-request:'||v_req.id::text,0));
  SELECT COALESCE(jsonb_agg(jsonb_build_object('meal_date',mrd.meal_date,'breakfast',mrd.breakfast,'lunch',mrd.lunch,'dinner',mrd.dinner) ORDER BY mrd.meal_date),'[]'::jsonb)
    INTO v_before FROM public.meal_request_days mrd WHERE mrd.request_id=v_req.id AND mrd.is_current=true;

  UPDATE public.meal_request_days SET is_current=false,updated_at=now()
   WHERE request_id=v_req.id AND is_current=true;
  INSERT INTO public.meal_request_days(request_id,meal_date,breakfast,lunch,dinner,is_current)
  SELECT v_req.id,x.meal_date,x.breakfast,x.lunch,x.dinner,true
  FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)
  ORDER BY x.meal_date;

  SELECT COALESCE(jsonb_agg(jsonb_build_object('meal_date',x.meal_date,'breakfast',x.breakfast,'lunch',x.lunch,'dinner',x.dinner) ORDER BY x.meal_date),'[]'::jsonb)
    INTO v_after FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric);
  UPDATE public.meal_requests SET manager_updated_at=now(),manager_updated_by=v_actor,
    manager_update_note=COALESCE(NULLIF(trim(p_note),''),'ম্যানেজার কর্তৃক অনুরোধ সমন্বয়'),updated_at=now()
   WHERE id=v_req.id;
  INSERT INTO public.meal_request_edit_audit(hostel_id,period_id,request_id,member_id,edited_by_membership_id,action,note,before_days,after_days)
   VALUES(v_hostel,v_req.period_id,v_req.id,v_req.member_id,v_actor,'submitted_request_edit',
     COALESCE(NULLIF(trim(p_note),''),'ম্যানেজার কর্তৃক অনুরোধ সমন্বয়'),v_before,v_after);
  INSERT INTO public.notifications(hostel_id,notification_type,title,body,reference_type,reference_id,created_by,target_membership_id)
   VALUES(v_hostel,'system','আপনার মিল অনুরোধ আপডেট হয়েছে',
     COALESCE(NULLIF(trim(p_note),''),'ম্যানেজার আপনার একই মিল অনুরোধের পরিমাণ সমন্বয় করেছেন।')||' অনুরোধটি বাতিল বা ডুপ্লিকেট করা হয়নি; ম্যানেজারের পরবর্তী অনুমোদন/সিদ্ধান্ত একই রিকোয়েস্টে থাকবে.',
     'meal_request',v_req.id,v_actor,v_req.member_id);
  RETURN jsonb_build_object('request_id',v_req.id,'updated',true,'status',v_req.status,'manager_updated_at',now());
END;
$submitted_request_edit$;
REVOKE ALL ON FUNCTION public.manager_update_submitted_meal_request(uuid,jsonb,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.manager_update_submitted_meal_request(uuid,jsonb,text) TO authenticated;

DROP FUNCTION IF EXISTS public.manager_edit_approved_meal_request(uuid,jsonb);
CREATE OR REPLACE FUNCTION public.manager_edit_approved_meal_request(
  p_request_id uuid,
  p_days jsonb,
  p_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $function$
DECLARE
  v_req public.meal_requests;
  v_actor uuid;
  v_hostel uuid;
  v_period public.monthly_periods;
  v_day public.daily_meal_days;
  d record;
  v_expected integer := 0;
  v_count integer := 0;
  v_final integer := 0;
  v_pending integer := 0;
  v_existing public.daily_meal_records;
  v_before_days jsonb := '[]'::jsonb;
BEGIN
  PERFORM private.assert_authenticated();
  v_actor:=private.current_membership_id(true);
  v_hostel:=private.current_hostel_id(true);

  SELECT * INTO v_req
  FROM public.meal_requests
  WHERE id=p_request_id
    AND hostel_id=v_hostel
    AND request_type='normal'::meal_request_type
    AND status='approved'::request_status
  FOR UPDATE;

  IF v_req.id IS NULL THEN
    RAISE EXCEPTION USING message='এই অনুমোদিত মিল রিকোয়েস্টটি পাওয়া যায়নি।';
  END IF;

  IF v_req.origin='manager_self' THEN
    RAISE EXCEPTION USING message='ম্যানেজারের নিজের মিলের জন্য “আমার মিল” বা Emergency Override ব্যবহার করুন।';
  END IF;

  IF NOT private.can_manage_period(v_req.period_id) THEN
    RAISE EXCEPTION USING message='এই রিকোয়েস্ট এডিট করার অনুমতি নেই।';
  END IF;

  SELECT * INTO v_period FROM public.monthly_periods WHERE id=v_req.period_id;
  IF v_period.id IS NULL OR v_period.status <> 'running'::public.month_status THEN
    RAISE EXCEPTION USING message='এই অনুরোধের মাস আর চালু নেই। চূড়ান্ত/পুরোনো মাসের জন্য আর্কাইভ সংশোধনের পথ ব্যবহার করুন।';
  END IF;
  IF jsonb_typeof(p_days) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION USING message='মিলের দিনের তালিকা সঠিক নয়।';
  END IF;

  SELECT count(*)::int INTO v_count
  FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric);
  v_expected:=v_req.end_date-v_req.start_date+1;

  IF coalesce(v_count,0)<>v_expected THEN
    RAISE EXCEPTION USING message='রিকোয়েস্টের সব দিনের মিল তথ্য একসাথে দিতে হবে।';
  END IF;

  IF EXISTS(
    SELECT 1
    FROM (
      SELECT meal_date, count(*) c
      FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)
      GROUP BY meal_date
    ) z
    WHERE z.c>1
  ) THEN
    RAISE EXCEPTION USING message='একই তারিখ একবারের বেশি দেওয়া যাবে না।';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('manager-request-edit:'||v_req.member_id::text||':'||v_req.period_id::text,0));

  -- Requests may only be edited through this path before each affected day is finalized.
  IF EXISTS (
    SELECT 1
    FROM public.daily_meal_days dmd
    WHERE dmd.hostel_id=v_hostel
      AND dmd.period_id=v_req.period_id
      AND dmd.meal_date BETWEEN v_req.start_date AND v_req.end_date
      AND (dmd.status='finalized'::public.meal_day_status OR now() >= dmd.finalizes_at)
  ) THEN
    RAISE EXCEPTION USING message='এই অনুরোধে চূড়ান্ত/সময় পেরোনো দিনের মিল আছে। Final Meal Correction / archive correction ব্যবহার করুন।';
  END IF;

  IF EXISTS(
    SELECT 1
    FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)
    WHERE x.meal_date<v_req.start_date OR x.meal_date>v_req.end_date
  ) THEN
    RAISE EXCEPTION USING message='রিকোয়েস্টের নির্ধারিত তারিখের বাইরে কোনো দিন এডিট করা যাবে না।';
  END IF;

  FOR d IN SELECT * FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric) LOOP
    SELECT * INTO v_day
    FROM public.daily_meal_days
    WHERE hostel_id=v_hostel AND period_id=v_req.period_id AND meal_date=d.meal_date
    FOR UPDATE;

    IF v_day.id IS NULL THEN
      RAISE EXCEPTION USING message='নির্বাচিত দিনের meal day পাওয়া যায়নি।';
    END IF;

    IF d.breakfast IS NULL OR d.lunch IS NULL OR d.dinner IS NULL
       OR d.breakfast<0 OR d.lunch<0 OR d.dinner<0
       OR d.breakfast>50 OR d.lunch>50 OR d.dinner>50 THEN
      RAISE EXCEPTION USING message='মিলের পরিমাণ সঠিক নয়।';
    END IF;

    -- Any previously-approved late override is superseded by this explicit
    -- manager edit. Keep the audit row as void rather than deleting it.
    UPDATE public.meal_late_overrides
    SET status='void',
        reason=coalesce(reason,'')||CASE WHEN coalesce(reason,'')='' THEN '' ELSE ' | ' END||'Superseded by manager request edit.',
        updated_at=now()
    WHERE daily_meal_day_id=v_day.id
      AND member_id=v_req.member_id
      AND status='approved';

    SELECT * INTO v_existing
    FROM public.daily_meal_records
    WHERE daily_meal_day_id=v_day.id AND member_id=v_req.member_id
    FOR UPDATE;

    IF now()>=v_day.finalizes_at OR v_day.status='finalized'::meal_day_status THEN
      UPDATE public.daily_meal_records
      SET planned_breakfast=d.breakfast,
          planned_lunch=d.lunch,
          planned_dinner=d.dinner,
          actual_breakfast=d.breakfast,
          actual_lunch=d.lunch,
          actual_dinner=d.dinner,
          final_breakfast=d.breakfast,
          final_lunch=d.lunch,
          final_dinner=d.dinner,
          cancelled=false,
          finalization_source='manager_edit',
          entered_by=v_actor,
          entered_at=now(),
          finalized_by=v_actor,
          finalized_at=now(),
          updated_at=now()
      WHERE id=v_existing.id;

      IF NOT FOUND THEN
        INSERT INTO public.daily_meal_records(
          hostel_id,period_id,daily_meal_day_id,member_id,
          planned_breakfast,planned_lunch,planned_dinner,
          actual_breakfast,actual_lunch,actual_dinner,
          final_breakfast,final_lunch,final_dinner,
          cancelled,finalization_source,entered_by,entered_at,finalized_by,finalized_at
        ) VALUES(
          v_hostel,v_req.period_id,v_day.id,v_req.member_id,
          d.breakfast,d.lunch,d.dinner,
          d.breakfast,d.lunch,d.dinner,
          d.breakfast,d.lunch,d.dinner,
          false,'manager_edit',v_actor,now(),v_actor,now()
        );
      END IF;

      UPDATE public.daily_meal_days
      SET status='finalized'::meal_day_status,
          finalized_at=coalesce(finalized_at,now()),
          updated_at=now()
      WHERE id=v_day.id AND status<>'finalized'::meal_day_status;

      PERFORM private.refresh_meal_snapshot(v_hostel,d.meal_date);
      v_final:=v_final+1;
    ELSE
      IF v_existing.id IS NULL THEN
        INSERT INTO public.daily_meal_records(
          hostel_id,period_id,daily_meal_day_id,member_id,
          planned_breakfast,planned_lunch,planned_dinner,
          cancelled,entered_by,entered_at
        ) VALUES(
          v_hostel,v_req.period_id,v_day.id,v_req.member_id,
          d.breakfast,d.lunch,d.dinner,false,v_actor,now()
        );
      ELSE
        UPDATE public.daily_meal_records
        SET planned_breakfast=d.breakfast,
            planned_lunch=d.lunch,
            planned_dinner=d.dinner,
            cancelled=false,
            entered_by=v_actor,
            entered_at=now(),
            updated_at=now()
        WHERE id=v_existing.id;
      END IF;
      PERFORM private.refresh_meal_snapshot(v_hostel,d.meal_date);
      v_pending:=v_pending+1;
    END IF;
  END LOOP;

  -- Preserve the exact before/after values for a manager audit trail.
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'meal_date',mrd.meal_date,'breakfast',mrd.breakfast,'lunch',mrd.lunch,'dinner',mrd.dinner
  ) ORDER BY mrd.meal_date),'[]'::jsonb)
  INTO v_before_days
  FROM public.meal_request_days mrd
  WHERE mrd.request_id=v_req.id AND mrd.is_current=true;

  -- Preserve request history while making the latest day rows authoritative.
  UPDATE public.meal_request_days
  SET is_current=false,updated_at=now()
  WHERE request_id=v_req.id AND is_current=true;

  FOR d IN SELECT * FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric) LOOP
    INSERT INTO public.meal_request_days(request_id,meal_date,breakfast,lunch,dinner,is_current)
    VALUES(v_req.id,d.meal_date,d.breakfast,d.lunch,d.dinner,true);
  END LOOP;

  UPDATE public.meal_requests
  SET updated_at=now(),
      manager_updated_at=now(),
      manager_updated_by=v_actor,
      manager_update_note=COALESCE(NULLIF(trim(p_note),''),'ম্যানেজার কর্তৃক অনুমোদিত মিল অনুরোধ আপডেট')
  WHERE id=v_req.id;

  INSERT INTO public.meal_request_edit_audit(
    hostel_id,period_id,request_id,member_id,edited_by_membership_id,action,note,before_days,after_days
  ) VALUES (
    v_hostel,v_req.period_id,v_req.id,v_req.member_id,v_actor,'approved_request_edit',
    COALESCE(NULLIF(trim(p_note),''),'ম্যানেজার কর্তৃক অনুমোদিত মিল অনুরোধ আপডেট'),
    v_before_days,
    COALESCE((SELECT jsonb_agg(jsonb_build_object(
      'meal_date',x.meal_date,'breakfast',x.breakfast,'lunch',x.lunch,'dinner',x.dinner
    ) ORDER BY x.meal_date) FROM jsonb_to_recordset(p_days) AS x(meal_date date,breakfast numeric,lunch numeric,dinner numeric)),'[]'::jsonb)
  );

  INSERT INTO public.notifications(
    hostel_id,notification_type,title,body,reference_type,reference_id,created_by,target_membership_id
  ) VALUES(
    v_hostel,'system','আপনার মিল রিকোয়েস্ট ম্যানেজার পরিবর্তন করেছেন',
    CASE WHEN v_final>0 AND v_pending=0
      THEN 'ম্যানেজার আপনার মিল পরিবর্তন করে final হিসাবেও যুক্ত করেছেন।'
      ELSE 'ম্যানেজার আপনার মিল রিকোয়েস্ট পরিবর্তন করেছেন। প্রযোজ্য দিনের ৯টার finalization-এ এটি final হবে।'
    END,
    'meal_request',v_req.id,v_actor,v_req.member_id
  );

  RETURN jsonb_build_object(
    'request_id',v_req.id,
    'updated',true,
    'finalized_immediately',v_final,
    'pending_finalization',v_pending
  );
END;
