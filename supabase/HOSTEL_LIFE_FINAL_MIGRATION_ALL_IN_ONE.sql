CREATE OR REPLACE FUNCTION public.platform_admin_set_hostel_status(p_hostel_id uuid,p_status text,p_reason text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,private,pg_catalog
AS $$
DECLARE v_old text;
BEGIN
  PERFORM private.assert_super_admin();
  IF p_status NOT IN ('active','suspended','soft_deleted') THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='স্ট্যাটাস সঠিক নয়।'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.hostels h WHERE h.id=p_hostel_id) THEN RAISE EXCEPTION USING MESSAGE='মেসটি পাওয়া যায়নি।'; END IF;
