-- Enforce blocked users and suspended/soft-deleted messes for direct writes and
-- existing SECURITY DEFINER RPCs (triggers run under the caller's JWT context).
CREATE OR REPLACE FUNCTION private.guard_platform_write()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path=public,private,pg_catalog
AS $$
DECLARE v_row jsonb; v_hostel uuid; v_user uuid; v_status text; v_parent uuid;
BEGIN
  IF auth.uid() IS NULL OR private.is_super_admin() THEN
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
  END IF;
  v_row := CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  v_user := NULLIF(v_row->>'user_id','')::uuid;
  v_status := v_row->>'status';
  IF TG_TABLE_NAME='hostels' THEN
    v_hostel := NULLIF(v_row->>'id','')::uuid;
  ELSE
    v_hostel := NULLIF(v_row->>'hostel_id','')::uuid;
  END IF;
  IF TG_TABLE_NAME='market_items' THEN
    v_parent := NULLIF(v_row->>'market_entry_id','')::uuid;
    SELECT me.hostel_id INTO v_hostel FROM public.market_entries me WHERE me.id=v_parent;
  ELSIF TG_TABLE_NAME='meal_request_days' THEN
    v_parent := NULLIF(v_row->>'request_id','')::uuid;
    SELECT mr.hostel_id INTO v_hostel FROM public.meal_requests mr WHERE mr.id=v_parent;
  ELSIF TG_TABLE_NAME='notification_states' THEN
    v_parent := NULLIF(v_row->>'notification_id','')::uuid;
    SELECT n.hostel_id INTO v_hostel FROM public.notifications n WHERE n.id=v_parent;
  ELSIF TG_TABLE_NAME='period_assistant_managers' THEN
    v_parent := NULLIF(v_row->>'period_id','')::uuid;
    SELECT mp.hostel_id INTO v_hostel FROM public.monthly_periods mp WHERE mp.id=v_parent;
  END IF;

  IF private.is_platform_user_blocked(auth.uid()) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='এই অ্যাকাউন্টটি প্ল্যাটফর্ম অ্যাডমিন দ্বারা ব্লক করা হয়েছে।';
  END IF;
  IF TG_TABLE_NAME='hostel_memberships' AND TG_OP<>'DELETE' AND v_user IS NOT NULL
     AND v_status='active' AND private.is_platform_user_blocked(v_user) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='ব্লক করা ব্যবহারকারীকে সক্রিয় মেম্বার হিসেবে যুক্ত করা যাবে না।';
  END IF;
  IF v_hostel IS NOT NULL AND EXISTS (
    SELECT 1 FROM private.platform_hostel_controls c WHERE c.hostel_id=v_hostel AND c.status IN ('suspended','soft_deleted')
  ) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='এই মেসটি সাময়িকভাবে স্থগিত বা বন্ধ করা হয়েছে।';
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
REVOKE ALL ON FUNCTION private.guard_platform_write() FROM PUBLIC, anon, authenticated;

DO $platform_triggers$
DECLARE v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'hostels','hostel_memberships','monthly_periods','daily_meal_days','daily_meal_records',
    'daily_meal_snapshots','ledger_transactions','market_entries','market_items','meal_requests',
    'meal_request_days','meal_late_overrides','khala_money_entries','notifications',
    'archive_edit_permissions','monthly_summaries','period_assistant_managers','notification_states'
  ] LOOP
    IF to_regclass(format('public.%I',v_table)) IS NOT NULL THEN
      EXECUTE format('DROP TRIGGER IF EXISTS hostel_life_platform_access_guard ON public.%I',v_table);
      EXECUTE format('CREATE TRIGGER hostel_life_platform_access_guard BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION private.guard_platform_write()',v_table);
    END IF;
  END LOOP;
END;
